GROUPS = {
    "1": "一、分析样本：中国设计通史与观念史",
    "2": "二、设计史学史与方法论研究",
    "3": "三、专门史：节点检验的材料来源",
    "4": "四、世界与全球设计史参照",
}


def index_sources():
    out = {}
    for dp, _dn, fns in os.walk(SRC):
        for fn in fns:
            if fn.lower().endswith(".pdf"):
                out.setdefault(fn, os.path.join(dp, fn))
    return out


def main():
    src_index = index_sources()
    problems = []
    total = 0
    for no, author, title, typ, files, note in PLAN:
        for fn in files:
            p = src_index.get(fn)
            if not p:
                problems.append(f"{no}: 源文件缺失 {fn}")
            else:
                total += os.path.getsize(p)

    for no, author, title, typ, files, note in PLAN:
        if not files:
            status = "非PDF资料" if typ in ("会议", "网页", "课程资料") else "未检出"
            print(f"{no}\t{status}\t{author}\t{title}")
            continue
        for fn in files:
            print(f"{no}\t{os.path.getsize(src_index.get(fn, '')) if fn in src_index else 0:>10d}\t{fn}")
    print(f"\n条目 {len(PLAN)}；有 PDF {sum(1 for p in PLAN if p[4])}；"
          f"文件 {sum(len(p[4]) for p in PLAN)}；合计 {total / 1024 / 1024:.1f} MB")
    for p in problems:
        print(" -", p)
    if problems:
        return

    if "--copy" not in sys.argv:
        return
    os.makedirs(DST, exist_ok=True)
    for no, author, title, typ, files, note in PLAN:
        for fn in files:
            shutil.copy2(src_index[fn], os.path.join(DST, RENAME.get(fn, fn)))
    print(f"Copied into {DST}")

    L = []
    L.append("# 相关研究书目 PDF 对照索引")
    L.append("")
    L.append("**生成日期**：2026-10-22  ")
    L.append(f"**清单**：`{LIST_MD}`（59 条）  ")
    L.append(f"**来源**：`{SRC}`（D 盘全盘 PDF 文件名检索后确认的已入藏本）  ")
    L.append("**结果**：38 条有对应 PDF（40 个文件）；18 条未检出 PDF；3 条为会议／网页／课程资料，无 PDF。  ")
    L.append("**命名**：`作者_书名_年份.pdf`，不带领取编号；条目与文件的对应见本表。  ")
    L.append("")
    for g in ("1", "2", "3", "4"):
        L.append(f"## {GROUPS[g]}")
        L.append("")
        L.append("| 序号 | 作者 | 书名／题名 | 状态 | PDF 文件 | 备注 |")
        L.append("| --- | --- | --- | --- | --- | --- |")
        for no, author, title, typ, files, note in PLAN:
            if not no.startswith(g + "-"):
                continue
            if files:
                status = "已复制"
                fcell = "、".join(f"`{RENAME.get(x, x)}`" for x in files)
            elif typ in ("会议", "网页", "课程资料"):
                status = "非PDF资料"
                fcell = "—"
            else:
                status = "未检出"
                fcell = "—"
            L.append(f"| {no} | {author} | {title} | {status} | {fcell} | {note} |")
        L.append("")
    L.append("## 未检出条目（18 条）")
    L.append("")
    L.append("以下条目在 D 盘 PDF 文件名索引中无对应文件，须另行取得：")
    L.append("")
    for no, author, title, typ, files, note in PLAN:
        if not files and typ not in ("会议", "网页", "课程资料"):
            L.append(f"- **{no}** {author}《{title}》——{note}")
    L.append("")
    with open(os.path.join(DST, "00_书目清单对照索引.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(L))
    print("Wrote 00_书目清单对照索引.md")


if __name__ == "__main__":
    main()
